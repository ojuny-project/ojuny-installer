def fix_btrfs_subvolumes(hardware_config, partitions):
    root_is_btrfs = any(
        part.get("mountPoint") == "/" and part.get("fs") == "btrfs"
        for part in partitions
    )
    if not root_is_btrfs:
        return hardware_config

    for mount_point, subvolume in {"/home": "home", "/nix": "nix"}.items():
        pattern = r'(fileSystems\."{}"[^;]*"subvol=)[^"]*"'.format(
            re.escape(mount_point)
        )
        hardware_config = re.sub(
            pattern,
            '\\g<1>{subvolume}"'.format(subvolume=subvolume),
            hardware_config,
            flags=re.DOTALL,
        )
    return hardware_config


def read_kernel_latest():
    try:
        parser = configparser.ConfigParser()
        parser.read("/etc/nixos-generate-config.conf")
        return parser["Defaults"]["Kernel"] == "latest"
    except Exception:
        return False


def extra_boot_lines(root, partitions, firmware):
    lines = []
    if read_kernel_latest():
        lines.append("boot.kernelPackages = pkgs.linuxPackages_latest;")

    luks_device_lines = []
    for part in partitions:
        if (
            part.get("claimed") is True
            and part.get("fsName") in ("luks", "luks2")
            and part.get("device") is not None
            and part.get("luksMapperName")
            and part.get("uuid")
        ):
            luks_device_lines.append(
                'boot.initrd.luks.devices."{}".device = "/dev/disk/by-uuid/{}";'.format(
                    part.get("luksMapperName"), part.get("uuid")
                )
            )

    for part in partitions:
        if (
            part.get("fs") not in ("linuxswap", "swap")
            or part.get("device") is None
            or not part.get("luksMapperName")
            or not part.get("uuid")
        ):
            continue
        line = 'boot.initrd.luks.devices."{}".device = "/dev/disk/by-uuid/{}";'.format(
            part.get("luksMapperName"), part.get("uuid")
        )
        if line not in luks_device_lines:
            luks_device_lines.append(line)

    lines += luks_device_lines

    root_is_encrypted = any(
        part.get("mountPoint") == "/" and part.get("fsName") in ("luks", "luks2")
        for part in partitions
    )
    boot_part = next(
        (part for part in partitions if part.get("mountPoint") == "/boot"), None
    )
    boot_is_partition = boot_part is not None
    boot_is_encrypted = (
        boot_is_partition and boot_part.get("fsName") in ("luks", "luks2")
    )

    if firmware != "efi" and (
        (boot_is_partition and boot_is_encrypted)
        or (root_is_encrypted and not boot_is_partition)
    ):
        keyfile = os.path.join(root, "boot", "crypto_keyfile.bin")
        run_command([cmd("pkexec"), cmd("mkdir"), "-p", os.path.dirname(keyfile)])
        run_command(
            [
                cmd("pkexec"),
                cmd("dd"),
                "bs=512",
                "count=4",
                "if=/dev/random",
                "of=" + keyfile,
                "iflag=fullblock",
            ]
        )
        run_command([cmd("pkexec"), cmd("chmod"), "600", keyfile])
        lines.append('boot.initrd.secrets."/boot/crypto_keyfile.bin" = null;')
        lines.append("boot.loader.grub.enableCryptodisk = true;")

        for part in partitions:
            if (
                part.get("luksMapperName")
                and part.get("device") is not None
                and (
                    part.get("claimed") is True
                    or part.get("fs") in ("linuxswap", "swap")
                )
            ):
                mapper = part.get("luksMapperName")
                lines.append(
                    'boot.initrd.luks.devices."{}".keyFile = "/boot/crypto_keyfile.bin";'.format(
                        mapper
                    )
                )
                passphrase = part.get("luksPassphrase")
                run_command(
                    [
                        cmd("pkexec"),
                        cmd("cryptsetup"),
                        "luksConvertKey",
                        "--hash",
                        "sha256",
                        "--pbkdf",
                        "pbkdf2",
                        part["device"],
                    ],
                    input=passphrase,
                )
                run_command(
                    [
                        cmd("pkexec"),
                        cmd("cryptsetup"),
                        "luksAddKey",
                        "--hash",
                        "sha256",
                        "--pbkdf",
                        "pbkdf2",
                        part["device"],
                        keyfile,
                    ],
                    input=passphrase,
                )

    return lines


def write_extra_file(lines):
    handle = tempfile.NamedTemporaryFile(
        mode="w", delete=False, prefix="ojuny-boot-"
    )
    try:
        handle.write("\n".join(lines) + "\n")
        handle.close()
        return handle.name
    except Exception:
        handle.close()
        raise


def configure_template(
    clone,
    runtime_clone,
    hostname,
    username,
    fullname,
    hashed_password,
    shell,
    version,
    hardware,
    firmware_type,
    device,
    extra_lines,
):
    global_storage = libcalamares.globalstorage
    configuration_path = os.path.join(clone, "modules/07-system/01-configuration.nix")

    with open(configuration_path) as handle:
        configuration = handle.read()

    configuration = replace_once(
        configuration,
        r'networking\.hostName = "[^"]*";',
        "networking.hostName = {hostname};".format(hostname=nix_string(hostname)),
        "networking.hostName",
        required=True,
    )
    configuration = replace_once(
        configuration,
        r'system\.stateVersion = "[^"]*";',
        "system.stateVersion = {version};".format(version=nix_string(version)),
        "system.stateVersion",
        required=True,
    )

    region = global_storage.value("locationRegion")
    zone = global_storage.value("locationZone")
    if region and zone:
        configuration = replace_once(
            configuration,
            r'time\.timeZone = "[^"]*";',
            "time.timeZone = {zone};".format(zone=nix_string(region + "/" + zone)),
            "time.timeZone",
        )

    locale_conf = global_storage.value("localeConf") or {}
    locale = (locale_conf.get("LANG") or "").split("/")[0]
    if locale:
        configuration = replace_once(
            configuration,
            r'i18n\.defaultLocale = "[^"]*";',
            "i18n.defaultLocale = {locale};".format(locale=nix_string(locale)),
            "i18n.defaultLocale",
        )

    keymap = global_storage.value("keyboardVConsoleKeymap") or global_storage.value(
        "keyboardLayout"
    )
    if keymap:
        configuration = replace_once(
            configuration,
            r'console\.keyMap = "[^"]*";',
            "console.keyMap = {keymap};".format(keymap=nix_string(keymap.strip())),
            "console.keyMap",
        )

    write_file(configuration_path, configuration)

    write_file(
        os.path.join(clone, "modules/01-users/01-user.nix"),
        user_module(username, fullname, hashed_password, shell, version),
    )
    write_file(
        os.path.join(clone, "modules/07-system/00-host.nix"),
        host_module(hostname, runtime_clone),
    )
    write_file(
        os.path.join(clone, "modules/07-system/00-hardware.nix"),
        hardware_module(hardware, firmware_type, device, extra_lines),
    )


